/**
 * Product identity fixtures.
 *
 * ---------------------------------------------------------------------------
 * WHAT THESE ARE AND ARE NOT
 * ---------------------------------------------------------------------------
 * These describe PRODUCT IDENTITIES (brand, name, variant, size, pack count) —
 * the kind of information printed on a package. They contain NO PRICES.
 *
 * `gtin` is `null` on every entry. Real GTINs were not available to this
 * environment, and inventing barcode numbers would let a fabricated identifier
 * flow into a Level-1 "exact UPC match" claim. Populate `gtin` only from a
 * scanned barcode or a retailer product page that publishes it.
 *
 * The set is chosen to include deliberately hard neighbours — same brand,
 * different size / variant / product line — because those are the cases a
 * matcher has to get wrong-answer-proof, not the easy ones.
 */

